/**
 * Scénarios E2E « texte » — données partagées entre la suite automatisée
 * et le catalogue manuel (docs/scenarios-e2e-texte.md).
 *
 * Chaque scénario cible le pipeline : détection → scoring → politique → masquage
 * (même chemin que A1 / A2 / Inspect).
 */
import type { Channel, Policy, PolicyAction } from "@acg/shared";

export interface TextE2EScenario {
  id: string;
  title: string;
  /** Groupe pour la matrice de couverture */
  group:
    | "allow"
    | "warn"
    | "mask"
    | "block"
    | "channel"
    | "masking"
    | "degraded"
    | "extract";
  text: string;
  channel: Channel;
  /** Hostname web ou commande CLI */
  hostnameOrCommand: string;
  user: {
    department: string;
    departmentRiskLevel: "low" | "moderate" | "high";
    jurisdiction: string;
  };
  /** Actions acceptées (plusieurs si le score peut basculer de bande) */
  expectedActions: PolicyAction[];
  /** Types d'entités qui doivent être présents (sous-ensemble) */
  expectEntityTypes?: string[];
  /** Sous-chaînes qui ne doivent plus apparaître après MASK */
  mustNotAppearIfMasked?: string[];
  /** Nom de politique attendu (prefix match) si action ≠ ALLOW */
  expectedPolicyNameIncludes?: string;
  notes?: string;
}

